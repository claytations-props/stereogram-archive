#!/usr/bin/env python3
"""Generate the catalog outputs from the per-item v2 records.

Since Phase 1, records/STA-####.json (schema/catalog-v2.schema.json)
is the catalog of record. This generator is the ONLY writer of:

  data.json         - the v1 item shape plus the appended Phase 1
                      fields; the full catalog, still published for
                      fallback/external consumers
  catalog-v2.json   - the full v2 records as a single array
  browse.json       - Phase 2A: one slim entry per item with exactly
                      the fields index.html reads at browse time
  vr.json           - Phase 2A: one slim entry per item with exactly
                      the fields vr.html reads
  search/index.json - Phase 2A: chunked full-text search index
                      manifest, with search/chunk-####.json chunk
                      files in accession blocks of 250

All outputs are deterministic: running the generator twice on the
same records produces byte-identical files. Records are validated
structurally against the v2 schema before anything is written; any
error aborts the build with nothing written.

Asset base (Phase 2 readiness): ASSET_BASE below is the single place
the public base URL for locally hosted assets is configured. With
the default '' the generated asset references stay relative, exactly
as today. When Part B moves the rectified pairs (and the thumbnail
ladders) to an external host, setting ASSET_BASE (here or via
--asset-base) to that base URL makes the generator emit the records'
rect references — in data.json and vr.json — under the base. The
thumbnail ladders generated by tools/build_thumbs.py will be served
under the same base with these URL patterns (the ladders' on-disk
layout mirrors them):

  {base}thumbs/<STA>/w<width>.jpg        (original scan ladder)
  {base}thumbs-rect/<STA>/w<width>.jpg   (rectified pair ladder)

Usage: python3 tools/build_catalog.py [--records records]
                                      [--out-data data.json]
                                      [--out-v2 catalog-v2.json]
                                      [--out-browse browse.json]
                                      [--out-vr vr.json]
                                      [--out-search-dir search]
                                      [--asset-base URL]
The render_* functions are importable (tools/validate_catalog.py
--v2 uses them for its in-sync check).
"""
import argparse, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import v2fields

BASE = Path(__file__).parent.parent
ID_RE = re.compile(r'^STA-\d{4}$')

# Phase 2 asset hosting: see the module docstring. Default '' keeps
# every generated asset reference relative, exactly as before Part B.
ASSET_BASE = 'https://archive.org/download/stereogram-archive-images/'

# Intended public URL patterns for the thumbnail ladders under
# ASSET_BASE (tools/build_thumbs.py writes the matching directory
# layout). Not emitted anywhere yet — Part B wires the pages to them.
THUMB_URL_PATTERN = '{base}thumbs/{id}/w{width}.jpg'
THUMB_RECT_URL_PATTERN = '{base}thumbs-rect/{id}/w{width}.jpg'
THUMB_WIDTHS = (250, 500, 1000)

# Series labels as shown by index.html (CATS/CATLABEL there). The
# search haystack includes the labels exactly as the page builds it;
# keep the two in step.
CAT_LABELS = {
    'water': 'Falls & Rivers',
    'mountains': 'Mountains & Canyons',
    'cities': 'Cities & Towns',
    'war': 'Civil War',
    'world': 'Around the World',
    'people': 'People & Comedy',
    'oddities': 'Oddities',
}

SEARCH_BLOCK = 250

# Field sets for the Phase 2A slim outputs, in data.json key order.
# Each set is exactly what the consuming page reads (audited against
# index.html / vr.html field usage; see docs/DATA_DICTIONARY.md).
BROWSE_FIELDS = ['title', 'place', 'year', 'sy', 'era', 'cats',
                 'blurb', 'img', 'id', 'coll', 'depth']
VR_FIELDS = ['title', 'place', 'year', 'cats', 'img', 'full', 'id',
             'rect', 'coll', 'va', 'f', 'cond', 'creator',
             'collection_name']

_TYPE_CHECKS = {
    'string': lambda v: isinstance(v, str),
    'integer': lambda v: isinstance(v, int) and not isinstance(v, bool),
    'number': lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
    'array': lambda v: isinstance(v, list),
    'object': lambda v: isinstance(v, dict),
    'null': lambda v: v is None,
}


def _type_ok(spec, v):
    t = spec.get('type')
    if t is None:
        return True
    types = t if isinstance(t, list) else [t]
    return any(_TYPE_CHECKS[x](v) for x in types)


def validate_record(rec, schema, tag):
    """Stdlib structural validation of one record against the v2
    schema (types, required, enums, patterns), in the same style as
    tools/validate_catalog.py. Returns a list of error strings."""
    errors = []
    props = schema['properties']
    for field in schema['required']:
        if field not in rec:
            errors.append(f'{tag}: missing required field "{field}"')
    for field, spec in props.items():
        if field not in rec:
            continue
        v = rec[field]
        ref = spec.get('$ref')
        if ref == '#/$defs/nullableString':
            if not (v is None or isinstance(v, str)):
                errors.append(f'{tag}: "{field}" must be a string or null')
            continue
        if ref == '#/$defs/nullableInteger':
            if not (v is None or (isinstance(v, int) and not isinstance(v, bool))):
                errors.append(f'{tag}: "{field}" must be an integer or null')
            continue
        if ref == '#/$defs/px':
            if not isinstance(v, dict):
                errors.append(f'{tag}: "px" must be an object')
                continue
            for k in ('s', 'L', 'R', 'g', 'ar'):
                if k not in v:
                    errors.append(f'{tag}: px missing "{k}"')
            for k, want in (('L', 6), ('R', 6), ('g', 2)):
                vv = v.get(k)
                if not (isinstance(vv, list) and len(vv) == want
                        and all(isinstance(x, (int, float))
                                and not isinstance(x, bool) for x in vv)):
                    errors.append(f'{tag}: px.{k} must be {want} numbers')
            continue
        if not _type_ok(spec, v):
            errors.append(f'{tag}: "{field}" has the wrong type')
            continue
        enum = spec.get('enum')
        if enum and v not in enum:
            errors.append(f'{tag}: "{field}" value {v!r} not in enum')
        items = spec.get('items') or {}
        ienum = items.get('enum')
        if ienum and isinstance(v, list):
            for el in v:
                if el not in ienum:
                    errors.append(f'{tag}: "{field}" value {el!r} not in enum')
        pat = spec.get('pattern')
        if pat and isinstance(v, str) and not re.match(pat, v):
            errors.append(f'{tag}: "{field}" value {v!r} fails pattern')
    extra = set(rec) - set(props)
    if extra:
        errors.append(f'{tag}: unexpected field(s) {sorted(extra)}')
    if isinstance(rec.get('id'), str) and not ID_RE.match(rec['id']):
        errors.append(f'{tag}: id does not match ^STA-\\d{{4}}$')
    if rec.get('facets') != rec.get('cats'):
        errors.append(f'{tag}: facets must mirror cats in v2')
    if 'tags' in rec:
        vocab = _tag_vocabulary()
        if not isinstance(rec['tags'], list):
            errors.append(f'{tag}: "tags" must be an array')
        else:
            for t in rec['tags']:
                if not isinstance(t, str) or t not in vocab:
                    errors.append(f'{tag}: tag {t!r} is not in '
                                  'tools/tag_vocabulary.json')
    return errors


_TAG_VOCABULARY = None


def _tag_vocabulary():
    """The flat term set of the controlled index vocabulary
    (tools/tag_vocabulary.json), loaded once."""
    global _TAG_VOCABULARY
    if _TAG_VOCABULARY is None:
        doc = json.loads((Path(__file__).parent
                          / 'tag_vocabulary.json').read_text())
        _TAG_VOCABULARY = {t for terms in doc['groups'].values()
                           for t in terms}
    return _TAG_VOCABULARY


def load_records(records_dir):
    schema = json.loads(
        (BASE / 'schema' / 'catalog-v2.schema.json').read_text())
    files = sorted(Path(records_dir).glob('STA-*.json'))
    if not files:
        raise RuntimeError(f'no records found in {records_dir}')
    records, errors = [], []
    for f in files:
        rec = json.loads(f.read_text())
        errors.extend(validate_record(rec, schema, f.stem))
        records.append(rec)
    records.sort(key=lambda r: r['id'])
    ids = [r['id'] for r in records]
    if len(ids) != len(set(ids)):
        errors.append('duplicate record ids')
    if [f.stem for f in files] != ids:
        errors.append('record filenames do not match record ids in order')
    if errors:
        raise RuntimeError('record validation failed:\n  ' + '\n  '.join(errors))
    return records


def _asset_url(path, asset_base):
    """Join a repo-relative asset path onto the asset base. With the
    default empty base the path is returned unchanged."""
    if not asset_base:
        return path
    return asset_base.rstrip('/') + '/' + path.lstrip('/')


def render_data_json(records, asset_base=ASSET_BASE):
    items = []
    for r in records:
        item = v2fields.generated_item(r)
        if asset_base:
            item['rect'] = _asset_url(item['rect'], asset_base)
        items.append(item)
    return json.dumps(items, indent=1, ensure_ascii=False)


def render_catalog_v2(records):
    return json.dumps(records, indent=1, ensure_ascii=False)


def _slim(rec, fields, asset_base=''):
    out = {}
    for k in fields:
        v = rec[k]
        if k == 'rect' and asset_base:
            v = _asset_url(v, asset_base)
        out[k] = v
    return out


def render_browse_json(records):
    """Slim per-item entries with exactly the fields index.html reads
    at browse time (grid, shelves, finding aid, register, hero,
    Recent Accessions, browse-field filtering/sorting)."""
    items = [_slim(r, BROWSE_FIELDS) for r in records]
    return json.dumps(items, indent=1, ensure_ascii=False)


def render_vr_json(records, asset_base=ASSET_BASE):
    """Slim per-item entries with exactly the fields vr.html reads
    (set derivation, browse wall, reading state, metadata card)."""
    items = [_slim(r, VR_FIELDS, asset_base) for r in records]
    return json.dumps(items, indent=1, ensure_ascii=False)


def haystack(rec):
    """The full-text search string for one record, byte-for-byte the
    haystack index.html built from data.json before Phase 2A:
    title, place, year, blurb, id, coll, and the series labels,
    lowercased. Since the tagging pilot, a record's optional `tags`
    (the INDEX layer: machine-assigned subject terms from
    tools/tag_vocabulary.json, never catalog text) are appended so
    pictured content is searchable too."""
    labels = ' '.join(CAT_LABELS.get(c, c) for c in rec['cats'])
    text = (rec['title'] + ' ' + rec['place'] + ' ' + rec['year'] + ' '
            + (rec['blurb'] or '') + ' ' + rec['id'] + ' ' + rec['coll']
            + ' ' + labels)
    if rec.get('tags'):
        text += ' ' + ' '.join(rec['tags'])
    return text.lower()


def render_search(records):
    """(manifest_text, {chunk_filename: text}) for the chunked search
    index: accession blocks of SEARCH_BLOCK records, each chunk a
    JSON array of [id, haystack] pairs, one pair per line."""
    chunks = {}
    entries = []
    for start in range(0, len(records), SEARCH_BLOCK):
        block = records[start:start + SEARCH_BLOCK]
        name = f'chunk-{start // SEARCH_BLOCK + 1:04d}.json'
        lines = [json.dumps([r['id'], haystack(r)], ensure_ascii=False)
                 for r in block]
        chunks[name] = '[\n' + ',\n'.join(lines) + '\n]'
        entries.append({'file': name, 'from': block[0]['id'],
                        'to': block[-1]['id'], 'items': len(block)})
    manifest = {'version': 1, 'count': len(records),
                'blockSize': SEARCH_BLOCK, 'chunks': entries}
    return json.dumps(manifest, indent=1, ensure_ascii=False), chunks


def write_outputs(records, out_dir, asset_base=ASSET_BASE):
    """Write every generated output under out_dir. Returns the list
    of paths written. Stale search chunk files are removed so the
    search/ directory always matches the manifest exactly."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    search_dir = out_dir / 'search'
    search_dir.mkdir(parents=True, exist_ok=True)
    manifest_text, chunks = render_search(records)
    wanted = set(chunks)
    for stale in search_dir.glob('chunk-*.json'):
        if stale.name not in wanted:
            stale.unlink()
    written = []
    for name, text in [('data.json', render_data_json(records, asset_base)),
                       ('catalog-v2.json', render_catalog_v2(records)),
                       ('browse.json', render_browse_json(records)),
                       ('vr.json', render_vr_json(records, asset_base))]:
        p = out_dir / name
        p.write_text(text)
        written.append(p)
    p = search_dir / 'index.json'
    p.write_text(manifest_text)
    written.append(p)
    for name, text in chunks.items():
        p = search_dir / name
        p.write_text(text)
        written.append(p)
    return written


def main():
    ap = argparse.ArgumentParser(description='Generate the catalog '
                                               'outputs from records/')
    ap.add_argument('--records', default=str(BASE / 'records'))
    ap.add_argument('--out-dir', default=str(BASE),
                    help='directory the outputs are written to '
                         '(default: the repo root)')
    ap.add_argument('--asset-base', default=ASSET_BASE,
                    help='public base URL for locally hosted assets '
                         '(default: empty = relative, as today)')
    args = ap.parse_args()
    records = load_records(args.records)
    written = write_outputs(records, args.out_dir, args.asset_base)
    for p in written:
        print(f'generated {p} ({p.stat().st_size} bytes)')
    print(f'from {len(records)} records')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except RuntimeError as e:
        print(f'ERROR: {e}')
        sys.exit(1)
